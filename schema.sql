-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    email TEXT PRIMARY KEY,
    last_active TIMESTAMPTZ DEFAULT NOW(),
    last_lat DOUBLE PRECISION,
    last_lng DOUBLE PRECISION,
    last_accuracy DOUBLE PRECISION,
    last_location_time TIMESTAMPTZ
);

-- 2. MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT,
    sender TEXT NOT NULL,
    seen BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    type TEXT DEFAULT 'text',
    file_url TEXT,
    file_name TEXT
);

-- 3. TYPING STATUS TABLE
CREATE TABLE IF NOT EXISTS public.typing_status (
    user_email TEXT PRIMARY KEY,
    is_typing BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TASKS TABLE
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    is_completed BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. NOTES TABLE
CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- ENABLE ROW LEVEL SECURITY (RLS) & OPEN POLICIES
-- ========================================================

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.typing_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;

-- Allow all authenticated & anon users to read/write for Draftly
DROP POLICY IF EXISTS "Public access users" ON public.users;
CREATE POLICY "Public access users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access messages" ON public.messages;
CREATE POLICY "Public access messages" ON public.messages FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access typing_status" ON public.typing_status;
CREATE POLICY "Public access typing_status" ON public.typing_status FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access tasks" ON public.tasks;
CREATE POLICY "Public access tasks" ON public.tasks FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access notes" ON public.notes;
CREATE POLICY "Public access notes" ON public.notes FOR ALL USING (true) WITH CHECK (true);

-- ========================================================
-- ENABLE REALTIME
-- ========================================================

-- Enable full replica identity for updates/deletes if not already
ALTER TABLE public.messages REPLICA IDENTITY FULL;
ALTER TABLE public.typing_status REPLICA IDENTITY FULL;
ALTER TABLE public.users REPLICA IDENTITY FULL;

-- Add tables to supabase_realtime publication
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'messages'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'typing_status'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.typing_status;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'users'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.users;
    END IF;
END $$;

-- ========================================================
-- STORAGE BUCKET: draftly-media
-- ========================================================

-- Insert bucket if not exists
INSERT INTO storage.buckets (id, name, public)
VALUES ('draftly-media', 'draftly-media', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Bucket storage policies for upload and read
DROP POLICY IF EXISTS "Public Read Draftly Media" ON storage.objects;
CREATE POLICY "Public Read Draftly Media" ON storage.objects
FOR SELECT USING (bucket_id = 'draftly-media');

DROP POLICY IF EXISTS "Public Insert Draftly Media" ON storage.objects;
CREATE POLICY "Public Insert Draftly Media" ON storage.objects
FOR INSERT WITH CHECK (bucket_id = 'draftly-media');

DROP POLICY IF EXISTS "Public Update Draftly Media" ON storage.objects;
CREATE POLICY "Public Update Draftly Media" ON storage.objects
FOR UPDATE USING (bucket_id = 'draftly-media');

DROP POLICY IF EXISTS "Public Delete Draftly Media" ON storage.objects;
CREATE POLICY "Public Delete Draftly Media" ON storage.objects
FOR DELETE USING (bucket_id = 'draftly-media');
